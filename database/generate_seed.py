"""
Generates database/04_seed_data.sql  (DEMO data - clearly synthetic)
====================================================================
* crops catalogue  : 22 crops; suitability envelopes LEARNED from the training
                     data (ml/models/model_meta.json) + agronomic attributes
                     from ml/crop_knowledge.py
* farmers / plots  : fictional cooperative around Vellore, Tamil Nadu
* sensor nodes     : NODE-01 is the real breadboard node; NODE-02..06 are
                     simulated so the dashboard has something to show
* soil logs        : 10 days, one reading every 30 min per sensor node, built
                     around a real row of the processed dataset + diurnal cycle
                     + sensor noise + ~2 % injected faults; manual entries for
                     plots without a node; manual pH (Soil Health Card style)
                     for most plots
* cycles           : Kharif 2024 -> Kharif 2026, rotation-respecting, yields =
                     expected yield x area x U(0.65, 1.15); fertiliser at
                     typical doses with 2024-25 subsidised Indian MRPs

Timestamps of sensor logs are written RELATIVE to NOW() so the demo always
looks current whenever the database is (re)loaded.

Run:  python database/generate_seed.py      (needs ml/models/model_meta.json)
"""
import json
import sys
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ml"))
import crop_knowledge as ck                     # noqa: E402
from build_dataset import CROP_SOILS            # noqa: E402

rng = np.random.default_rng(2026)
OUT = ROOT / "database" / "04_seed_data.sql"
TODAY = date(2026, 10, 9)                        # reference date for cycle status
meta = json.loads((ROOT / "ml" / "models" / "model_meta.json").read_text())
env = meta["envelopes"]
data = pd.read_csv(ROOT / "data" / "processed" / "agrismart_sensor_dataset.csv")

sql = ["-- AUTO-GENERATED by database/generate_seed.py  -  DEMO DATA (synthetic)",
       "USE agrismart;", "SET FOREIGN_KEY_CHECKS = 0;",
       *[f"TRUNCATE TABLE {t};" for t in ["recommendation_items", "recommendation_runs", "treatments",
                                           "cultivation_cycles", "soil_health_logs", "sensor_nodes",
                                           "plots", "crops", "farmers"]],
       "SET FOREIGN_KEY_CHECKS = 1;", ""]


def q(v):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "NULL"
    if isinstance(v, (bool, np.bool_)):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        return f"{float(v):.4f}".rstrip("0").rstrip(".")
    if isinstance(v, date):
        return f"'{v.isoformat()}'"
    if isinstance(v, str) and v.startswith("NOW()"):
        return v
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, cols, rows, batch=500):
    for i in range(0, len(rows), batch):
        vals = ",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows[i:i + batch])
        sql.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{vals};")
    sql.append("")


# ------------------------------------------------------------------ crops
crop_names = sorted(ck.CROPS)
crop_id = {c: i + 1 for i, c in enumerate(crop_names)}
rows = []
for c in crop_names:
    i = ck.info(c); e = env[c]
    rows.append([crop_id[c], c, i["season"], i["family"], i["n_demand"], i["is_perennial"],
                 i["maturation_days"], i["expected_yield_kg_acre"],
                 *e["ph"], *e["moisture_pct"], *e["soil_temp_c"], *e["air_temp_c"], *e["humidity_pct"]])
insert("crops", ["crop_id", "crop_name", "season", "family", "n_demand", "is_perennial", "maturation_days",
                 "expected_yield_kg_acre", "ph_min", "ph_max", "moisture_min", "moisture_max",
                 "soil_temp_min", "soil_temp_max", "air_temp_min", "air_temp_max",
                 "humidity_min", "humidity_max"], rows)

# ---------------------------------------------------------------- farmers
farmers = [("Murugan K", "Katpadi"), ("Lakshmi R", "Gudiyatham"), ("Senthil Kumar P", "Arcot"),
           ("Kavitha S", "Ambur"), ("Ramesh V", "Anaicut"), ("Selvi M", "Katpadi"),
           ("Arjun D", "Pernambut"), ("Meena T", "Vaniyambadi"), ("Prakash N", "Arcot"),
           ("Revathi G", "Gudiyatham")]
insert("farmers", ["farmer_id", "full_name", "phone_no", "village", "coop_id"],
       [[i + 1, n, f"90000000{i + 1:02d}", v, "VLR-COOP-01"] for i, (n, v) in enumerate(farmers)])

# ------------------------------------------------------------------ plots
plot_specs = [  # farmer, name, acres, soil
    (1, "North field", 2.5, "Alluvial"), (1, "Canal plot", 1.2, "Alluvial"),
    (2, "Main field", 3.0, "Black"), (3, "East block", 1.8, "Red"),
    (3, "Tank-side plot", 2.2, "Alluvial"), (4, "Home field", 1.0, "Sandy"),
    (5, "Hill slope", 2.8, "Laterite"), (5, "Lower field", 1.5, "Red"),
    (6, "River plot", 2.0, "Alluvial"), (7, "Dry field", 3.5, "Sandy"),
    (8, "Cotton field", 4.0, "Black"), (8, "Orchard", 2.0, "Red"),
    (9, "South field", 1.6, "Black"), (10, "Coconut grove", 3.0, "Laterite"),
    (10, "Village plot", 0.8, "Alluvial"), (2, "Back field", 1.4, "Black"),
]
plots = []
for i, (f, n, a, s) in enumerate(plot_specs):
    plots.append([i + 1, f, n, a, s, round(12.92 + rng.uniform(-.12, .12), 6), round(79.13 + rng.uniform(-.18, .18), 6)])
insert("plots", ["plot_id", "farmer_id", "plot_name", "area_acres", "soil_type", "latitude", "longitude"], plots)
soil_of = {p[0]: p[4] for p in plots}
area_of = {p[0]: p[3] for p in plots}

# ------------------------------------------------------------ sensor nodes
node_plot = {"NODE-01": 1, "NODE-02": 3, "NODE-03": 4, "NODE-04": 6, "NODE-05": 7, "NODE-06": 11}
insert("sensor_nodes", ["node_id", "plot_id", "mac_address", "firmware_ver", "installed_on"],
       [[n, p, None, "1.0.0", date(2026, 8, 1) if n == "NODE-01" else date(2026, 9, 1)] for n, p in node_plot.items()])

# --------------------------------------------------------- cultivation cycles
SLOTS = [("Kharif", date(2024, 6, 20)), ("Rabi", date(2024, 11, 12)), ("Zaid", date(2025, 2, 25)),
         ("Kharif", date(2025, 6, 20)), ("Rabi", date(2025, 11, 12)), ("Zaid", date(2026, 2, 25)),
         ("Kharif", date(2026, 6, 20))]
ORCHARD = {12: "pomegranate", 14: "coconut"}       # perennial plots
cycles, treat = [], []
cid = tid = 0
FERT = {  # product: (N, P, K fraction, INR per kg)   - 2024-25 MRP (subsidised)
    "Urea (46-0-0)": (.46, 0, 0, 266.5 / 45), "DAP (18-46-0)": (.18, .46, 0, 1350 / 50),
    "MOP (0-0-60)": (0, 0, .60, 1700 / 50), "Farmyard manure": (.005, .002, .005, 1.5),
}


def add_treatments(c_id, crop, sow, area):
    global tid
    fam = ck.info(crop)["family"]
    plan = []
    if fam == "Legume":
        plan = [("DAP (18-46-0)", 40)]
    elif rng.random() < 0.8:  # 20 % of non-legume cycles: farmer skipped fertiliser
        plan = [("DAP (18-46-0)", 50), ("Urea (46-0-0)", float(rng.uniform(70, 110))), ("MOP (0-0-60)", 25)]
    if rng.random() < 0.3:
        plan.append(("Farmyard manure", 2000))
    for k, (prod, per_acre) in enumerate(plan):
        n, p, kk, price = FERT[prod]; qty = round(per_acre * area, 1); tid += 1
        treat.append([tid, c_id, sow + timedelta(days=0 if k == 0 else 25 + 10 * k),
                      "MANURE" if "manure" in prod else "FERTILISER", prod, qty,
                      round(qty * n, 2), round(qty * p, 2), round(qty * kk, 2), round(qty * price, 2)])
    if rng.random() < 0.5:
        tid += 1
        treat.append([tid, c_id, sow + timedelta(days=40), "PESTICIDE", "Neem oil 1500 ppm",
                      round(1.0 * area, 1), 0, 0, 0, round(450 * area, 2)])


for pid in range(1, len(plots) + 1):
    last_crop, free_from = None, date(2024, 1, 1)
    if pid in ORCHARD:
        crop = ORCHARD[pid]
        for yr in (2024, 2025):
            sow = date(yr, 1, 15); harv = sow + timedelta(days=ck.info(crop)["maturation_days"])
            cid += 1
            y = ck.info(crop)["expected_yield_kg_acre"] * area_of[pid] * rng.uniform(.65, 1.15)
            cycles.append([cid, pid, crop_id[crop], sow, harv, round(y, 1), "HARVESTED"])
            add_treatments(cid, crop, sow, area_of[pid])
        continue
    soil = soil_of[pid]
    for season, start in SLOTS:
        sow = start + timedelta(days=int(rng.integers(0, 20)))
        if sow < free_from or rng.random() < 0.2:      # still occupied, or fallow
            continue
        options = [c for c in crop_names if ck.info(c)["season"] == season and c != last_crop]
        wts = np.array([CROP_SOILS[c].get(soil, 0) for c in options])
        if wts.sum() == 0:
            continue
        crop = rng.choice(options, p=wts / wts.sum())
        days = ck.info(crop)["maturation_days"] + int(rng.integers(-8, 12))
        harv = sow + timedelta(days=days)
        cid += 1
        if harv > TODAY:
            cycles.append([cid, pid, crop_id[crop], sow, None, None, "GROWING"])
        else:
            fail = rng.random() < 0.04
            y = 0 if fail else ck.info(crop)["expected_yield_kg_acre"] * area_of[pid] * rng.uniform(.65, 1.15)
            cycles.append([cid, pid, crop_id[crop], sow, harv, round(y, 1), "FAILED" if fail else "HARVESTED"])
        add_treatments(cid, crop, sow, area_of[pid])
        last_crop, free_from = crop, harv + timedelta(days=7)
        if harv > TODAY:
            break

sql.append("-- cycles are inserted with the rotation trigger active: they respect it by construction")
insert("cultivation_cycles", ["cycle_id", "plot_id", "crop_id", "sow_date", "harvest_date", "yield_kg", "status"], cycles)
insert("treatments", ["treatment_id", "cycle_id", "applied_on", "category", "product_name", "qty_kg",
                      "n_kg", "p_kg", "k_kg", "cost_inr"], treat)

# --------------------------------------------------------------- soil logs
logs = []
STEP_MIN, DAYS = 30, 10
for pid in range(1, len(plots) + 1):
    soil = soil_of[pid]
    prof = data[data.soil_type == soil].sample(1, random_state=int(rng.integers(1e9))).iloc[0]
    node = next((n for n, p in node_plot.items() if p == pid), None)
    if node:
        n = DAYS * 24 * 60 // STEP_MIN
        for k in range(n):
            mins_ago = (n - 1 - k) * STEP_MIN + int(rng.integers(0, 3))
            hour = ((24 * 60 - (mins_ago % (24 * 60))) / 60 + 10) % 24   # approx local hour
            ang = 2 * np.pi * (hour - 9) / 24
            air = prof.air_temp_c + 4 * np.sin(ang) + rng.normal(0, 1)
            hum = np.clip(prof.humidity_pct - 8 * np.sin(ang) + rng.normal(0, 2.5), 10, 99)
            st = prof.soil_temp_c + 1.5 * np.sin(2 * np.pi * (hour - 12) / 24) + rng.normal(0, .25)
            mo = np.clip(prof.moisture_pct + rng.normal(0, 1.0), 0.5, 55)
            st = round(st / 0.0625) * 0.0625
            r = rng.random()
            if r < 0.006: st = -127.0           # DS18B20 disconnected
            elif r < 0.010: st = 85.0           # DS18B20 power-on value
            elif r < 0.016: mo = 0.0            # probe pulled out of soil
            elif r < 0.020: hum = min(99, hum + 30)
            logs.append([pid, node, f"NOW() - INTERVAL {mins_ago} MINUTE", "SENSOR",
                         round(float(mo), 1), float(st), float(round(air)), float(round(hum)), None, None])
    else:  # manual readings with a handheld kit, every ~2 days
        for d in (8, 6, 4, 2, 0):
            mins_ago = d * 1440 + int(rng.integers(0, 600))
            logs.append([pid, None, f"NOW() - INTERVAL {mins_ago} MINUTE", "MANUAL",
                         round(float(prof.moisture_pct + rng.normal(0, 1.2)), 1),
                         round(float(prof.soil_temp_c + rng.normal(0, .6)), 2),
                         float(round(prof.air_temp_c + rng.normal(0, 1.2))),
                         float(round(prof.humidity_pct + rng.normal(0, 3))), None, "handheld reading"])
    if pid not in (4, 10, 13, 16):                 # 4 plots have no pH -> sensor-only model
        days_ago = int(rng.integers(20, 120))
        logs.append([pid, None, f"NOW() - INTERVAL {days_ago} DAY", "MANUAL", None, None, None, None,
                     round(float(prof.ph + rng.normal(0, .08)), 2), "Soil Health Card pH (1:2.5 soil:water)"])
insert("soil_health_logs", ["plot_id", "node_id", "log_ts", "source", "moisture_pct", "soil_temp_c",
                            "air_temp_c", "humidity_pct", "ph_value", "note"], logs, batch=1000)

OUT.write_text("\n".join(sql))
print(f"wrote {OUT.relative_to(ROOT)}: {len(crop_names)} crops, {len(farmers)} farmers, {len(plots)} plots, "
      f"{len(node_plot)} nodes, {len(cycles)} cycles, {len(treat)} treatments, {len(logs)} soil logs")
